create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (char_length(username) between 3 and 20),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "Profiles readable by authenticated" on public.profiles;
create policy "Profiles readable by authenticated"
on public.profiles for select to authenticated using (true);

-- Profil dibuat otomatis saat user daftar (username dari metadata signUp)
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  base_name text;
  final_name text;
begin
  base_name := regexp_replace(
    coalesce(nullif(new.raw_user_meta_data->>'username', ''), split_part(new.email, '@', 1)),
    '[^a-zA-Z0-9_]', '', 'g'
  );
  if char_length(base_name) < 3 then
    base_name := 'player' || substr(replace(new.id::text, '-', ''), 1, 6);
  end if;
  base_name := left(base_name, 16);
  final_name := base_name;

  -- kalau bentrok, tambah suffix acak
  while exists (select 1 from public.profiles where lower(username) = lower(final_name)) loop
    final_name := base_name || floor(random() * 900 + 100)::int::text;
  end loop;

  insert into public.profiles (id, username) values (new.id, final_name);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

