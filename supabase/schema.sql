-- Peringkat: waktu terbaik per pemain per soal
create or replace function public.get_leaderboard(p_problem text, p_days int default null)
returns table (rank bigint, user_id uuid, username text, language text, best_seconds int)
language sql
stable
as $$
  with best as (
    select distinct on (s.user_id) s.user_id, s.language, s.elapsed_seconds
    from public.scores s
    where s.problem_id = p_problem
      and (p_days is null or s.created_at >= now() - make_interval(days => p_days))
    order by s.user_id, s.elapsed_seconds asc, s.created_at asc
  )
  select row_number() over (order by b.elapsed_seconds, p.username) as rank,
         b.user_id, p.username, b.language, b.elapsed_seconds
  from best b
  join public.profiles p on p.id = b.user_id
  order by 1
  limit 50;
$$;

-- Rata-rata waktu & jumlah pemain per soal
create or replace function public.get_problem_stats(p_problem text)
returns table (avg_seconds numeric, players bigint)
language sql
stable
as $$
  select round(avg(t.best)), count(*)
  from (
    select min(s.elapsed_seconds) as best
    from public.scores s
    where s.problem_id = p_problem
    group by s.user_id
  ) t;
$$;

