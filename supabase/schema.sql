-- ---------- DUEL 1v1 ----------
create table if not exists public.duels (
  id uuid primary key default gen_random_uuid(),
  problem_id text not null,
  player1 uuid not null references public.profiles(id) on delete cascade,
  player2 uuid references public.profiles(id) on delete cascade,
  status text not null default 'waiting'
    check (status in ('waiting', 'active', 'finished', 'cancelled')),
  started_at timestamptz,
  finished_at timestamptz,
  winner uuid references public.profiles(id),
  winner_seconds integer,
  created_at timestamptz not null default now()
);
create index if not exists duels_waiting_idx on public.duels (status, created_at);

create table if not exists public.duel_events (
  id bigint generated by default as identity primary key,
  duel_id uuid not null references public.duels(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  passed integer not null,
  total integer not null,
  created_at timestamptz not null default now()
);
create index if not exists duel_events_duel_idx on public.duel_events (duel_id, id);

alter table public.duels enable row level security;
alter table public.duel_events enable row level security;

-- Client hanya boleh MEMBACA duel miliknya. Semua penulisan lewat RPC di bawah.
drop policy if exists "Players read own duels" on public.duels;
create policy "Players read own duels"
on public.duels for select to authenticated
using (auth.uid() = player1 or auth.uid() = player2);

drop policy if exists "Players read own duel events" on public.duel_events;
create policy "Players read own duel events"
on public.duel_events for select to authenticated
using (exists (
  select 1 from public.duels d
  where d.id = duel_id and (auth.uid() = d.player1 or auth.uid() = d.player2)
));

-- Cari lawan: gabung ke duel yang menunggu, atau buat baru
create or replace function public.find_duel(p_problem text)
returns public.duels
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := auth.uid();
  d public.duels;
begin
  if me is null then raise exception 'Belum login'; end if;

  -- bersihkan duel menunggu yang basi (> 2 menit)
  update public.duels set status = 'cancelled'
  where status = 'waiting' and created_at < now() - interval '2 minutes';

  -- duel aktif yang terbengkalai (> 15 menit) dibatalkan
  update public.duels set status = 'cancelled'
  where status = 'active' and started_at < now() - interval '15 minutes';

  -- kalau saya sudah punya duel aktif/menunggu, lanjutkan itu
  select * into d from public.duels
  where (player1 = me or player2 = me) and status in ('waiting', 'active')
  order by created_at desc limit 1;
  if found then return d; end if;

  -- gabung ke duel orang lain
  select * into d from public.duels
  where status = 'waiting' and player1 <> me
  order by created_at asc
  limit 1
  for update skip locked;

  if found then
    update public.duels
    set player2 = me, status = 'active', started_at = now()
    where id = d.id
    returning * into d;
    return d;
  end if;

  insert into public.duels (problem_id, player1) values (p_problem, me)
  returning * into d;
  return d;
end;
$$;

create or replace function public.cancel_duel(p_duel uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.duels set status = 'cancelled'
  where id = p_duel and player1 = auth.uid() and status = 'waiting';
end;
$$;

-- Lapor progres test (dipakai buat feed & progress bar lawan)
create or replace function public.duel_progress(p_duel uuid, p_passed int, p_total int)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare me uuid := auth.uid();
begin
  if not exists (
    select 1 from public.duels
    where id = p_duel and status = 'active' and (player1 = me or player2 = me)
  ) then
    return;
  end if;
  insert into public.duel_events (duel_id, user_id, passed, total)
  values (p_duel, me, greatest(p_passed, 0), greatest(p_total, 1));
end;
$$;

-- Selesai: yang pertama memanggil ini menang. Waktu dihitung di SERVER.
create or replace function public.duel_finish(p_duel uuid, p_language text)
returns public.duels
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := auth.uid();
  d public.duels;
  secs int;
begin
  select * into d from public.duels
  where id = p_duel and (player1 = me or player2 = me)
  for update;

  if not found then raise exception 'Duel tidak ditemukan'; end if;
  if d.status <> 'active' then return d; end if;

  secs := greatest(1, floor(extract(epoch from (now() - d.started_at)))::int);

  update public.duels
  set status = 'finished', winner = me, winner_seconds = secs, finished_at = now()
  where id = d.id
  returning * into d;

  insert into public.scores (user_id, problem_id, language, elapsed_seconds, source)
  values (me, d.problem_id, coalesce(p_language, 'javascript'), secs, 'duel');

  return d;
end;
$$;

-- Menyerah: lawan otomatis menang (tanpa skor)
create or replace function public.duel_forfeit(p_duel uuid)
returns public.duels
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := auth.uid();
  d public.duels;
begin
  select * into d from public.duels
  where id = p_duel and (player1 = me or player2 = me)
  for update;
  if not found then raise exception 'Duel tidak ditemukan'; end if;
  if d.status <> 'active' then return d; end if;

  update public.duels
  set status = 'finished',
      winner = case when player1 = me then player2 else player1 end,
      finished_at = now()
  where id = d.id
  returning * into d;
  return d;
end;
$$;

